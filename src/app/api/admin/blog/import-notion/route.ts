export async function POST() {
  const user = await getCurrentUser();
  if (!user || user.role !== "ADMIN") return NextResponse.json({ error: "FORBIDDEN" }, { status: 403 });

  const results = [];
  for (const post of POSTS) {
    const saved = await db.blogPost.upsert({
      where: { slug: post.slug },
      create: { ...post, published: true },
      update: { title: post.title, excerpt: post.excerpt, body: post.body, published: true },
      select: { id: true, slug: true, title: true, published: true },
    });
    results.push(saved);
  }

  return NextResponse.json({ ok: true, imported: results });
}
